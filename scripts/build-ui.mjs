/** Bundle the offline 3D report; Python installations need no Node toolchain. */
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const license = await readFile(path.join(root, "node_modules/three/LICENSE"), "utf8");
const result = await build({
  absWorkingDir: root,
  entryPoints: ["ui/dimension-map.js"],
  outfile: "src/project_assess/static/dimension-map.generated.js",
  bundle: true,
  format: "iife",
  globalName: "PATDimensionMap",
  platform: "browser",
  target: "es2020",
  minify: true,
  write: !check,
  legalComments: "eof",
  banner: { js: `/*! Generated by npm run build:ui from ui/dimension-map.js.\nThree.js:\n${license.replaceAll("*/", "* /")}\n*/` },
});
const licensePath = path.join(root, "src/project_assess/static/THREE-LICENSE.txt");
if (check) {
  const current = await readFile(path.join(root, "src/project_assess/static/dimension-map.generated.js"));
  if (!current.equals(Buffer.from(result.outputFiles[0].contents)) || await readFile(licensePath, "utf8") !== license) {
    throw new Error("Bundled 3D assets are stale; run npm run build:ui and commit the result.");
  }
} else {
  await writeFile(licensePath, license);
}
